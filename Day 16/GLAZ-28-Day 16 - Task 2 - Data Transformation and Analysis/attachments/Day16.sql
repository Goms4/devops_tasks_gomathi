WITH ATTENDANCE_SUMMARY AS (
    SELECT
        EMPLOYEE_ID,
        COUNT(*) AS TOTAL_ATTENDANCE
    FROM CLEANED_ATTENDANCE
    GROUP BY EMPLOYEE_ID
),

PAYROLL_SUMMARY AS (
    SELECT
        EMPLOYEE_ID,
        SUM(NET_SALARY) AS TOTAL_PAYROLL
    FROM CLEANED_PAYROLL
    GROUP BY EMPLOYEE_ID
)

SELECT
    D.DEPARTMENT_NAME,

    SUM(COALESCE(A.TOTAL_ATTENDANCE, 0))
        AS TOTAL_ATTENDANCE,

    SUM(COALESCE(P.TOTAL_PAYROLL, 0))
        AS TOTAL_PAYROLL

FROM DEPARTMENTS D

LEFT JOIN EMPLOYEES E
    ON D.DEPARTMENT_NAME =
        CASE
            WHEN UPPER(TRIM(E.DEPARTMENT)) = 'IT'
                THEN 'Engineering'
            WHEN UPPER(TRIM(E.DEPARTMENT)) = 'SALES'
                THEN 'Operations'
            WHEN UPPER(TRIM(E.DEPARTMENT)) = 'HR'
                THEN 'Human Resources'
            ELSE E.DEPARTMENT
        END

LEFT JOIN ATTENDANCE_SUMMARY A
    ON E.EMPLOYEE_ID = A.EMPLOYEE_ID

LEFT JOIN PAYROLL_SUMMARY P
    ON E.EMPLOYEE_ID = P.EMPLOYEE_ID

GROUP BY
    D.DEPARTMENT_ID,
    D.DEPARTMENT_NAME

ORDER BY TOTAL_PAYROLL DESC;

