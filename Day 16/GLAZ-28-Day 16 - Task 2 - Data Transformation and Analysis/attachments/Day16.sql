    COUNT_IF(STATUS = 'ABSENT') AS ABSENT_DAYS,
    ROUND(
        100.0 * COUNT_IF(STATUS = 'PRESENT') / COUNT(*), 2
    ) AS ATTENDANCE_PERCENTAGE
FROM CLEANED_ATTENDANCE
GROUP BY EMPLOYEE_ID
ORDER BY ATTENDANCE_PERCENTAGE DESC;

SELECT
