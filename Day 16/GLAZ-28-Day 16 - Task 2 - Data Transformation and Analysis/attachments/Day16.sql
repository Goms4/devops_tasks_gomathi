CREATE OR REPLACE TABLE CLEANED_ATTENDANCE AS
SELECT
    ATTENDANCE_ID,
    EMPLOYEE_ID,
    TO_DATE(ATTENDANCE_DATE) AS ATTENDANCE_DATE,
    CHECK_IN,
    CHECK_OUT,
    UPPER(STATUS) AS STATUS,
    CASE
        WHEN STATUS = 'Present' THEN 1
        ELSE 0
    END AS ATTENDANCE_FLAG,
    CASE
        WHEN STATUS = 'Present'
        THEN DATEDIFF(MINUTE, CHECK_IN, CHECK_OUT)
        ELSE 0
    END AS WORKING_MINUTES
FROM ATTENDANCE
WHERE EMPLOYEE_ID IS NOT NULL
  AND ATTENDANCE_DATE IS NOT NULL;

SELECT * FROM CLEANED_ATTENDANCE;

CREATE OR REPLACE TABLE CLEANED_PAYROLL AS
SELECT
    PAYROLL_ID,
    EMPLOYEE_ID,
    TO_DATE(PAY_MONTH) AS PAY_MONTH,
    BASIC_SALARY,
    COALESCE(BONUS, 0) AS BONUS,
    COALESCE(DEDUCTIONS, 0) AS DEDUCTIONS,
    BASIC_SALARY + COALESCE(BONUS, 0)
        - COALESCE(DEDUCTIONS, 0) AS NET_SALARY
FROM PAYROLL
WHERE BASIC_SALARY >= 0
  AND EMPLOYEE_ID IS NOT NULL;

