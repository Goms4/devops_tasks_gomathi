CREATE OR REPLACE VIEW EMPLOYEE_ANALYTICS AS
SELECT
    E.EMPLOYEE_ID,
    E.EMPLOYEE_NAME,
    E.DEPARTMENT,
    D.LOCATION,
    COUNT(A.ATTENDANCE_ID) AS TOTAL_ATTENDANCE_DAYS,
    COUNT_IF(A.STATUS = 'PRESENT') AS PRESENT_DAYS,
    COUNT_IF(A.STATUS = 'ABSENT') AS ABSENT_DAYS,
    SUM(P.NET_SALARY) AS TOTAL_NET_SALARY
FROM EMPLOYEES E
LEFT JOIN DEPARTMENTS D
    ON UPPER(E.DEPARTMENT) = UPPER(D.DEPARTMENT_NAME)
LEFT JOIN CLEANED_ATTENDANCE A
    ON E.EMPLOYEE_ID = A.EMPLOYEE_ID
LEFT JOIN CLEANED_PAYROLL P
    ON E.EMPLOYEE_ID = P.EMPLOYEE_ID
GROUP BY
    E.EMPLOYEE_ID,
    E.EMPLOYEE_NAME,
    E.DEPARTMENT,
    D.LOCATION;

SELECT
    D.DEPARTMENT_NAME,
    COUNT(E.EMPLOYEE_ID) AS TOTAL_EMPLOYEES
FROM DEPARTMENTS D
LEFT JOIN EMPLOYEES E
    ON UPPER(D.DEPARTMENT_NAME) = UPPER(E.DEPARTMENT)
GROUP BY D.DEPARTMENT_NAME
ORDER BY TOTAL_EMPLOYEES DESC;

SELECT
